/**
 * Generates src/ai/preflopRanks.ts: the 169 starting hands ordered best to worst.
 *
 * Each hand's all-in equity is simulated against 1 random hand (heads-up) and
 * against 4 random hands (multiway). The two are normalized by their baselines
 * (50% and 20%) and averaged, which ranks hands sensibly for full-ring play:
 * small pairs and suited connectors land between their heads-up and multiway values.
 *
 *   npx tsx scripts/gen-preflop-ranks.ts [trials]
 */
import { writeFileSync } from 'node:fs';
import { makeCard, RANK_CHARS, type Card } from '../src/engine/cards';
import { evaluate } from '../src/engine/evaluator';
import { seededRng } from '../src/engine/rng';

const TRIALS = Number(process.argv[2] ?? 20000);
const rng = seededRng(20261116);

function equity(hole: Card[], opponents: number): number {
  const rest = Array.from({ length: 52 }, (_, i) => i).filter((c) => !hole.includes(c));
  let score = 0;
  const need = 5 + 2 * opponents;
  for (let t = 0; t < TRIALS; t++) {
    // Partial Fisher-Yates: draw `need` cards.
    for (let i = 0; i < need; i++) {
      const j = i + rng.int(rest.length - i);
      const tmp = rest[i]; rest[i] = rest[j]; rest[j] = tmp;
    }
    const board = rest.slice(0, 5);
    const mine = evaluate([...hole, ...board]);
    let best = 0, ties = 0, beaten = false;
    for (let o = 0; o < opponents; o++) {
      const v = evaluate([rest[5 + 2 * o], rest[6 + 2 * o], ...board]);
      if (v > mine) { beaten = true; break; }
      if (v === mine) ties++;
      best = Math.max(best, v);
    }
    if (!beaten) score += 1 / (ties + 1);
  }
  return score / TRIALS;
}

const hands: Array<{ code: string; combos: number; score: number; eq1: number; eq4: number }> = [];
for (let hi = 12; hi >= 0; hi--) {
  for (let lo = hi; lo >= 0; lo--) {
    const variants = hi === lo ? [['', 6]] : [['s', 4], ['o', 12]];
    for (const [suffix, combos] of variants as Array<[string, number]>) {
      const code = RANK_CHARS[hi] + RANK_CHARS[lo] + suffix;
      const hole = [makeCard(hi, 0), makeCard(lo, suffix === 's' ? 0 : 1)];
      const eq1 = equity(hole, 1);
      const eq4 = equity(hole, 4);
      hands.push({ code, combos, eq1, eq4, score: (eq1 / 0.5 + eq4 / 0.2) / 2 });
    }
  }
}
hands.sort((a, b) => b.score - a.score);

const lines = hands.map((h) => `  '${h.code}', // ${(h.eq1 * 100).toFixed(1)}% HU, ${(h.eq4 * 100).toFixed(1)}% vs 4`);
const out = `// Generated by scripts/gen-preflop-ranks.ts (${TRIALS} trials per hand). Edit the generator, not this list.
// The 169 starting hands from best to worst for full-ring play.
export const PREFLOP_ORDER: readonly string[] = [
${lines.join('\n')}
];
`;
writeFileSync(new URL('../src/ai/preflopRanks.ts', import.meta.url), out);
console.log('Top 20:', hands.slice(0, 20).map((h) => h.code).join(' '));
console.log('Bottom 10:', hands.slice(-10).map((h) => h.code).join(' '));
